def get_map():
    """Возвращает копию карты"""
    return [row[:] for row in GAME_MAP]


def is_buildable(col, row):
    """Можно ли строить на этой клетке"""
    if 0 <= row < len(GAME_MAP) and 0 <= col < len(GAME_MAP[0]):
        return GAME_MAP[row][col] == 0
    return False