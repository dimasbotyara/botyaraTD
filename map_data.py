def _generate_path_from_grid(grid):
    """Автоматически находит последовательность центров клеток дороги от входа (2) до выхода (3)"""
    rows = len(grid)
    cols = len(grid[0])
    
    start = None
    end = None
    for r in range(rows):
        for c in range(cols):
            if grid[r][c] == 2:
                start = (c, r)
            elif grid[r][c] == 3:
                end = (c, r)
                
    if not start or not end:
        return []
        
    visited = set()
    path_cells = [start]
    visited.add(start)
    
    current = start
    while current != end:
        cx, cy = current
        neighbors = [(cx+1, cy), (cx-1, cy), (cx, cy+1), (cx, cy-1)]
        found_next = False
        for nx, ny in neighbors:
            if 0 <= nx < cols and 0 <= ny < rows:
                if (nx, ny) not in visited and grid[ny][nx] in (1, 3):
                    visited.add((nx, ny))
                    path_cells.append((nx, ny))
                    current = (nx, ny)
                    found_next = True
                    break
        if not found_next:
            break
            
    # Конвертация в координаты пикселей (центр клетки)
    pixel_path = []
    for col, row in path_cells:
        px = col * CELL_SIZE + CELL_SIZE // 2
        py = row * CELL_SIZE + CELL_SIZE // 2
        pixel_path.append((px, py))
    return pixel_path


